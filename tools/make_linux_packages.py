#!/usr/bin/env python3
"""Build Linux distro packages (.deb, .rpm, .pkg.tar.zst) from a built bundle.

Expects ``dist/JLU-DrCOM-NG`` (produced by ``python build.py`` on Linux) and
outputs packages into ``release/``:

    jlu-drcom-ng_<version>_<deb_arch>.deb
    jlu-drcom-ng-<version>-1.<rpm_arch>.rpm
    jlu-drcom-ng-<version>-1-<arch>.pkg.tar.zst
"""

from __future__ import annotations

import argparse
import os
import pathlib
import platform
import re
import shutil
import subprocess
import sys
import tempfile
import time

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIST_DIR = ROOT / "dist" / "JLU-DrCOM-NG"
RELEASE_DIR = ROOT / "release"
LINUX_INSTALLER_DIR = ROOT / "installer" / "linux"


def source_version() -> str:
    init = ROOT / "drcom" / "__init__.py"
    m = re.search(r'__version__\s*=\s*"([^"]+)"', init.read_text(encoding="utf-8"))
    if not m:
        raise SystemExit("cannot read __version__ from drcom/__init__.py")
    return m.group(1)


def normalize_arch(machine: str | None = None) -> tuple[str, str, str]:
    """Return ``(uname_arch, deb_arch, rpm_arch)``."""
    m = (machine or platform.machine() or "x86_64").lower()
    if m in ("x86_64", "amd64", "x64"):
        return ("x86_64", "amd64", "x86_64")
    if m in ("aarch64", "arm64"):
        return ("aarch64", "arm64", "aarch64")
    return (m, m, m)


def render_deb_control(*, version: str, deb_arch: str, installed_kb: int) -> str:
    return (
        "Package: jlu-drcom-ng\n"
        f"Version: {version}\n"
        "Section: net\n"
        "Priority: optional\n"
        f"Architecture: {deb_arch}\n"
        f"Installed-Size: {max(1, installed_kb)}\n"
        "Maintainer: hZsFN <https://github.com/hZsFN/jlu-drcom-ng>\n"
        "Homepage: https://github.com/hZsFN/jlu-drcom-ng\n"
        "Depends: libc6, libssl3 | libssl3t64 | libssl1.1\n"
        "Recommends: libgtk-3-0, libnotify-bin, iproute2, systemd\n"
        "Description: Jilin University Dr.COM campus network client\n"
        " JLU DrCOM NG campus network authenticator for Jilin University with\n"
        " HUD UI, lightweight native drcomd core, CLI, and systemd --user support.\n"
    )


def render_arch_pkginfo(*, version: str, arch: str, installed_bytes: int) -> str:
    build_date = int(time.time())
    return (
        "# Generated by make_linux_packages.py\n"
        "pkgname = jlu-drcom-ng\n"
        "pkgbase = jlu-drcom-ng\n"
        f"pkgver = {version}-1\n"
        "pkgdesc = Jilin University Dr.COM campus network client (HUD GUI + native drcomd)\n"
        "url = https://github.com/hZsFN/jlu-drcom-ng\n"
        f"builddate = {build_date}\n"
        "packager = hZsFN <https://github.com/hZsFN/jlu-drcom-ng>\n"
        f"size = {max(1, installed_bytes)}\n"
        f"arch = {arch}\n"
        "license = AGPL-3.0-only\n"
        "depend = glibc\n"
        "depend = openssl\n"
        "depend = iproute2\n"
        "optdepend = gtk3: Flet desktop GUI support\n"
        "optdepend = libnotify: desktop notifications\n"
    )


def render_desktop_entry() -> str:
    return (
        "[Desktop Entry]\n"
        "Type=Application\n"
        "Name=JLU DrCOM NG\n"
        "Comment=Jilin University Campus Network Client\n"
        "Exec=/usr/bin/jlu-drcom-ng\n"
        "Icon=jlu-drcom-ng\n"
        "Terminal=false\n"
        "Categories=Network;Utility;\n"
        "StartupNotify=false\n"
    )


def _export_icon_png(dest: pathlib.Path) -> bool:
    ico = ROOT / "assets" / "app.ico"
    if not ico.is_file():
        return False
    try:
        from PIL import Image

        with Image.open(ico) as img:
            dest.parent.mkdir(parents=True, exist_ok=True)
            img.convert("RGBA").save(dest, format="PNG")
        return True
    except Exception:
        return False


def populate_stage_root(stage: pathlib.Path, dist_dir: pathlib.Path) -> int:
    """Create standard Linux FHS payload under *stage*; returns total bytes."""
    opt_dir = stage / "opt" / "jlu-drcom-ng"
    bin_dir = stage / "usr" / "bin"
    unit_dir = stage / "usr" / "lib" / "systemd" / "user"
    app_dir = stage / "usr" / "share" / "applications"
    icon_path = stage / "usr" / "share" / "icons" / "hicolor" / "256x256" / "apps" / "jlu-drcom-ng.png"
    doc_dir = stage / "usr" / "share" / "doc" / "jlu-drcom-ng"
    lic_dir = stage / "usr" / "share" / "licenses" / "jlu-drcom-ng"

    opt_dir.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(dist_dir, opt_dir, symlinks=True)

    main_bin = opt_dir / "JLU-DrCOM-NG"
    if main_bin.exists():
        os.chmod(main_bin, 0o755)

    # Ensure native drcomd binary is present and executable
    drcomd_candidates = [opt_dir / "drcomd", opt_dir / "_internal" / "drcomd"]
    drcomd_rel = None
    for cand in drcomd_candidates:
        if cand.is_file():
            os.chmod(cand, 0o755)
            drcomd_rel = "/opt/jlu-drcom-ng/" + str(cand.relative_to(opt_dir)).replace("\\", "/")
            break
    if drcomd_rel is None and (ROOT / "native" / "drcomd").is_file():
        shutil.copy2(ROOT / "native" / "drcomd", opt_dir / "drcomd")
        os.chmod(opt_dir / "drcomd", 0o755)
        drcomd_rel = "/opt/jlu-drcom-ng/drcomd"

    bin_dir.mkdir(parents=True, exist_ok=True)
    jlu_link = bin_dir / "jlu-drcom-ng"
    jlu_link.unlink(missing_ok=True)
    os.symlink("/opt/jlu-drcom-ng/JLU-DrCOM-NG", jlu_link)
    if drcomd_rel is not None:
        d_link = bin_dir / "drcomd"
        d_link.unlink(missing_ok=True)
        os.symlink(drcomd_rel, d_link)

    unit_dir.mkdir(parents=True, exist_ok=True)
    unit_tpl = (LINUX_INSTALLER_DIR / "jlu-drcom-ng.service.in").read_text(encoding="utf-8")
    unit_body = (
        unit_tpl.replace("@WORKING_DIR@", "/opt/jlu-drcom-ng")
        .replace("@EXEC_START@", "/usr/bin/jlu-drcom-ng --autostart --minimized")
    )
    (unit_dir / "jlu-drcom-ng.service").write_text(unit_body, encoding="utf-8", newline="\n")

    app_dir.mkdir(parents=True, exist_ok=True)
    (app_dir / "jlu-drcom-ng.desktop").write_text(
        render_desktop_entry(), encoding="utf-8", newline="\n"
    )
    _export_icon_png(icon_path)

    doc_dir.mkdir(parents=True, exist_ok=True)
    lic_dir.mkdir(parents=True, exist_ok=True)
    for doc_src, dst_name in (
        (ROOT / "LICENSE", "copyright"),
        (ROOT / "README.md", "README.md"),
        (ROOT / "docs" / "troubleshooting.md", "troubleshooting.md"),
    ):
        if doc_src.is_file():
            shutil.copy2(doc_src, doc_dir / dst_name)
    if (ROOT / "LICENSE").is_file():
        shutil.copy2(ROOT / "LICENSE", lic_dir / "LICENSE")

    total_bytes = 0
    for p in stage.rglob("*"):
        if p.is_file() and not p.is_symlink():
            total_bytes += p.stat().st_size
    return total_bytes


def build_deb(stage: pathlib.Path, *, version: str, deb_arch: str, total_bytes: int) -> pathlib.Path:
    if not shutil.which("dpkg-deb"):
        raise RuntimeError("dpkg-deb not found")
    with tempfile.TemporaryDirectory(prefix="drcom-deb-") as tmp:
        pkg_root = pathlib.Path(tmp) / "pkg"
        shutil.copytree(stage, pkg_root, symlinks=True)
        debian_dir = pkg_root / "DEBIAN"
        debian_dir.mkdir(parents=True, exist_ok=True)
        (debian_dir / "control").write_text(
            render_deb_control(version=version, deb_arch=deb_arch, installed_kb=total_bytes // 1024),
            encoding="utf-8",
            newline="\n",
        )
        postinst = (
            "#!/bin/sh\nset -e\n"
            "if command -v update-desktop-database >/dev/null 2>&1; then\n"
            "  update-desktop-database -q /usr/share/applications || true\n"
            "fi\n"
        )
        postinst_path = debian_dir / "postinst"
        postinst_path.write_text(postinst, encoding="utf-8", newline="\n")
        os.chmod(postinst_path, 0o755)

        out = RELEASE_DIR / f"jlu-drcom-ng_{version}_{deb_arch}.deb"
        RELEASE_DIR.mkdir(parents=True, exist_ok=True)
        out.unlink(missing_ok=True)
        subprocess.run(
            ["dpkg-deb", "--root-owner-group", "--build", str(pkg_root), str(out)],
            check=True,
        )
        return out


def build_rpm(stage: pathlib.Path, *, version: str, rpm_arch: str) -> pathlib.Path:
    if not shutil.which("rpmbuild"):
        raise RuntimeError("rpmbuild not found")
    with tempfile.TemporaryDirectory(prefix="drcom-rpm-") as tmp:
        topdir = pathlib.Path(tmp) / "rpmbuild"
        for sub in ("BUILD", "RPMS", "SOURCES", "SPECS", "SRPMS"):
            (topdir / sub).mkdir(parents=True, exist_ok=True)
        spec_tpl = (LINUX_INSTALLER_DIR / "jlu-drcom-ng.spec.in").read_text(encoding="utf-8")
        spec_text = (
            spec_tpl.replace("@VERSION@", version.replace("-", "_"))
            .replace("@STAGE_DIR@", str(stage))
        )
        spec_path = topdir / "SPECS" / "jlu-drcom-ng.spec"
        spec_path.write_text(spec_text, encoding="utf-8", newline="\n")
        subprocess.run(
            [
                "rpmbuild",
                "-bb",
                "--target",
                rpm_arch,
                "--define",
                f"_topdir {topdir}",
                str(spec_path),
            ],
            check=True,
        )
        built = list((topdir / "RPMS").rglob("*.rpm"))
        if not built:
            raise RuntimeError("rpmbuild produced no .rpm file")
        out = RELEASE_DIR / f"jlu-drcom-ng-{version}-1.{rpm_arch}.rpm"
        RELEASE_DIR.mkdir(parents=True, exist_ok=True)
        shutil.copy2(built[0], out)
        return out


def build_arch_pkg(stage: pathlib.Path, *, version: str, arch: str, total_bytes: int) -> pathlib.Path:
    if not shutil.which("bsdtar"):
        raise RuntimeError("bsdtar (libarchive-tools) not found")
    with tempfile.TemporaryDirectory(prefix="drcom-arch-") as tmp:
        pkg_root = pathlib.Path(tmp) / "pkg"
        shutil.copytree(stage, pkg_root, symlinks=True)
        (pkg_root / ".PKGINFO").write_text(
            render_arch_pkginfo(version=version, arch=arch, installed_bytes=total_bytes),
            encoding="utf-8",
            newline="\n",
        )
        entries = [".PKGINFO"] + sorted(p.name for p in stage.iterdir())
        subprocess.run(
            [
                "bsdtar",
                "-czf",
                ".MTREE",
                "--format=mtree",
                "--options=!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link",
                *entries,
            ],
            cwd=pkg_root,
            env={**os.environ, "LANG": "C"},
            check=True,
        )
        out = RELEASE_DIR / f"jlu-drcom-ng-{version}-1-{arch}.pkg.tar.zst"
        RELEASE_DIR.mkdir(parents=True, exist_ok=True)
        out.unlink(missing_ok=True)
        subprocess.run(
            [
                "bsdtar",
                "--zstd",
                "-cf",
                str(out),
                ".PKGINFO",
                ".MTREE",
                *entries[1:],
            ],
            cwd=pkg_root,
            check=True,
        )
        return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dist-dir", type=pathlib.Path, default=DIST_DIR)
    parser.add_argument("--version", default="")
    args = parser.parse_args()

    if sys.platform == "win32":
        raise SystemExit("Linux distro packages must be built on Linux.")
    if not args.dist_dir.exists():
        raise SystemExit(f"{args.dist_dir} not found -- run `python build.py --fetch-runtime` first")

    version = args.version or source_version()
    uname_arch, deb_arch, rpm_arch = normalize_arch()
    with tempfile.TemporaryDirectory(prefix="drcom-linux-stage-") as stage_tmp:
        stage = pathlib.Path(stage_tmp) / "root"
        total_bytes = populate_stage_root(stage, args.dist_dir)
        deb = build_deb(stage, version=version, deb_arch=deb_arch, total_bytes=total_bytes)
        print(f"  deb   {deb.name} ({deb.stat().st_size / 1048576:.1f} MB)")
        rpm = build_rpm(stage, version=version, rpm_arch=rpm_arch)
        print(f"  rpm   {rpm.name} ({rpm.stat().st_size / 1048576:.1f} MB)")
        arch_pkg = build_arch_pkg(stage, version=version, arch=uname_arch, total_bytes=total_bytes)
        print(f"  arch  {arch_pkg.name} ({arch_pkg.stat().st_size / 1048576:.1f} MB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
